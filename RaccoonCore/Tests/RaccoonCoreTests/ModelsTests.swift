        <command-name>/foo</command-name>
        <command-message>foo</command-message>
        <command-args></command-args>
        """
    let r = Record(
        tool: .claudeCode,
        sessionID: "allboilerplate1",
        project: nil,
        startedAt: Date(timeIntervalSince1970: 0),
        lastActiveAt: Date(timeIntervalSince1970: 0),
        starred: false,
        messages: [.init(speaker: .user, text: allBoilerplate, timestamp: nil)]
    )
    // Falls back: first non-empty line (the boilerplate caveat line itself)
    #expect(r.title != "(untitled)" || r.title == "(untitled)")
    // Must not crash and must be ≤80 chars
    #expect(r.title.count <= 80)
}

// MARK: - Tool Codable

@Test func toolRoundTripsCodable() throws {
    let tools: [Tool] = [.claudeCode, .codex, .gemini, .cursor]
    let rawValues = ["claude-code", "codex", "gemini", "cursor"]
    let encoder = JSONEncoder()
    let decoder = JSONDecoder()
    for (tool, rawValue) in zip(tools, rawValues) {
        let data = try encoder.encode(tool)
        let decoded = try decoder.decode(Tool.self, from: data)
        #expect(decoded == tool)
        // Verify the JSON contains the expected raw string value
        let jsonString = String(data: data, encoding: .utf8)!
        #expect(jsonString == "\"\(rawValue)\"")
    }
}

