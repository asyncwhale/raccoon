// MARK: - Record.title

@Test func recordComputesTitleFromFirstUserMessage() {
    let r = Record(
        tool: .claudeCode,
        sessionID: "s1",
        project: "demo",
        startedAt: Date(timeIntervalSince1970: 0),
        lastActiveAt: Date(timeIntervalSince1970: 60),
        starred: false,
        messages: [.init(speaker: .user, text: "docker compose up fails port 5432", timestamp: nil)]
    )
    #expect(r.title == "docker compose up fails port 5432")
    #expect(r.tool.label == "Claude Code")
    #expect(Speaker.user.label == "User")
}

